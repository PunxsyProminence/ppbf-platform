/**
 * THE WALL — the board on the gym's television.
 *
 * This is not a page in the sense the other 68 are. Nobody signs into it,
 * nobody taps it, and nobody is standing closer than about fifteen feet. So it
 * breaks the house shell on purpose:
 *
 *   - No RoleStandaloneView. That shell brings a session bar, a breadcrumb
 *     trail, an Operations link and a Shadow chat button -- four controls on a
 *     screen with no pointer attached to it. The only controls here are the
 *     pair box and, once paired, the sound switch, both worked with the remote. GlobalRoleHeader stands down on
 *     this route for the same reason.
 *   - No hover states and no focus rings, because there is no cursor and no
 *     keyboard. Every element here is text.
 *   - The type starts where the desk surfaces stop. The φ ladder's top rung is
 *     --t-5xl at 80.9px, which is a hero size on a laptop; here it is the
 *     BODY size for a name, and the clock sits two rungs above it. globals.css
 *     already continues the ladder past the named rungs (--text-7xl through
 *     --text-9xl, generated by √φ), which is exactly what a wall needs and what
 *     nothing else in the app had a use for.
 *   - Nothing scrolls. The viewport is the page: h-screen, overflow hidden, and
 *     every list hard-capped server-side so a busy night cannot push the
 *     marquee off the bottom of a 16:9 panel.
 *
 * It is the ink ground (Law 6, staff side) in .room--floor: brick and caged
 * lamps, which is the room this screen is physically bolted to.
 */

/** Steady state: the board is a live read, and thirty seconds is live enough. */
export const WALL_POLL_MS = 30_000;
/**
 * While a round timer is set and not ended, the paired TV asks every five seconds instead
 * (WO-N1-04): a coach's Start, Pause or End reaches the wall within one short poll, and the start
 * bell can still ring. Twelve reads a minute, inside the TV read budget of sixty
 * (gymTvs.ts GYM_TV_READ_MAX_PER_KEY).
 */
export const WALL_ROUND_POLL_MS = 5_000;
/** A round start the TV learns about this many seconds late still rings; older is past. */
export const WALL_ROUND_FRESH_SECONDS = 7;

/**
 * After a failure, ask again SOONER, not later. A wall coming back within five
 * seconds of the network returning is the difference between "the screen was
 * out for a moment" and "the screen is broken". The ramp exists only so a
 * genuinely dead backend is not hammered forever.
 */
export function nextPollDelayMs(consecutiveFailures: number, roundsLive = false): number {
  // roundsLive after a failure means the paired read itself answered (only the board missed): the
  // timer is good, so the short poll holds and a coach's press reaches the wall in time.
  if (consecutiveFailures <= 0 || roundsLive) return roundsLive ? WALL_ROUND_POLL_MS : WALL_POLL_MS;
  return Math.min(5_000 * 2 ** (consecutiveFailures - 1), WALL_POLL_MS);
}

/** Five minutes without a good read: say so. Twenty: stop claiming. */
export const WALL_STALE_MS = 5 * 60_000;
export const WALL_ABANDON_MS = 20 * 60_000;

export type WallHealth = 'fresh' | 'stale' | 'abandoned' | 'never';

/**
 * How much the board is still allowed to assert.
 *
 * "Who is on the floor" is the one panel that rots: a list from forty minutes
 * ago is not a stale fact, it is a false one -- it names children as being in a
 * room they may have left. So past WALL_ABANDON_MS the board stops showing it
 * and stands down to the crest and the clock, which are true regardless.
 */
export function boardHealth(lastGoodAtMs: number | null, nowMs: number): WallHealth {
  if (lastGoodAtMs === null) return 'never';
  const age = nowMs - lastGoodAtMs;
  if (age >= WALL_ABANDON_MS) return 'abandoned';
  if (age >= WALL_STALE_MS) return 'stale';
  return 'fresh';
}

/**
 * WHICH BOARD THIS SCREEN GETS (OD-2026-10-07-008, Jason: "Paired gym TV
 * only"). Two reads, one poll:
 *
 *   1. GET /api/pilot/tv/session, with the device cookie a pairing code set
 *      (path /api/pilot/tv, so it rides with this request and no other). 200
 *      means this television is paired: the body carries the full board --
 *      initials per the name mode, milestone crossings, 'everywhere' notices.
 *   2. 401 TV_NOT_PAIRED means it is not. The screen then reads the public
 *      board from GET /api/pilot/wall: today's classes and a head count. No
 *      names, no initials, no milestones, gym_notices only.
 *
 * A 401 is not a failure for the board's health: an unpaired wall that read
 * its public board is a wall that is up. Any other non-2xx is.
 *
 * The public board is folded into the WallBoard shape with EMPTY people lists
 * (publicToBoard) so one render tree serves both. The fold is built from the
 * public fields by name, never by spreading the payload, so a name that
 * somehow arrived on the public channel would be dropped here as well as
 * refused by the server; wallDisplay.test.tsx pins that.
 */
interface PairedResponse {
  session?: { run_id?: string; timer?: RoundTimerView | null } | null;
  board?: WallBoard | null;
  board_status?: 'ok' | 'unavailable';
  /**
   * The gym's live quotes, paired TV only (#1462 Q-A). [] means the local sayings; null (a failed
   * quotes read) or absent means keep the quotes this screen last read, so the line does not flip.
   */
  quotes?: LibraryQuote[] | null;
}

interface PublicResponse {
  ok?: boolean;
  board?: WallPublicBoard;
}

export function publicToBoard(board: WallPublicBoard): WallBoard {
  return {
    generated_at: board.generated_at,
    gym_day: board.gym_day,
    time_zone: board.time_zone,
    // 'off' is the mode whose rendering is "N people training": the count is
    // real, the names are withheld. Exactly the public rule.
    name_mode: 'off',
    sessions: board.sessions,
    on_floor: [],
    on_floor_total: board.on_floor_total,
    marquee: [],
    notice: board.notice,
  };
}

/**
 * What stays on screen when this television has just been told it is NOT
 * paired and the public read then failed too. The last board may have been a
 * paired one, with initials and a marquee on it, and a 401 is the server
 * saying this screen may no longer show those: a coach pressed Disconnect, or
 * the key was revoked. So the people come off at once -- the classes, the
 * count and the notice stay, dated like any other last-good board -- rather
 * than riding out the twenty-minute abandon window (reviewer A).
 */
export function withoutPeople(board: WallBoard): WallBoard {
  return { ...board, name_mode: 'off', on_floor: [], marquee: [] };
}

/** Thrown by readBoard when the paired read answered 401 and the public read then failed. */
export class UnpairedReadError extends Error {
  constructor() {
    super('unavailable');
    this.name = 'UnpairedReadError';
  }
}

/** The live run's round timer as the paired read gave it. Never on the public read. */
export interface WallRoundTimer {
  runId: string;
  view: RoundTimerView;
}

/**
 * Thrown by readBoard when the paired read worked but its board did not (the server's best-effort
 * miss). The round timer in that same answer is good and is kept: a coach's Pause must still reach
 * the wall while the board is having trouble.
 */
export class BoardMissError extends Error {
  readonly timer: WallRoundTimer | null;
  constructor(timer: WallRoundTimer | null) {
    super('unavailable');
    this.name = 'BoardMissError';
    this.timer = timer;
  }
}

/**
 * Fast polling while a timer is set and not ended. That includes a set whose rounds are all done:
 * the coach's next Start on the same run must reach the wall within a short poll, or its start bell
 * would be too late to ring. An ended timer, or none, goes back to the thirty-second poll.
 */
export function roundsAreLive(timer: WallRoundTimer | null): boolean {
  return timer !== null && timer.view.state !== 'ended';
}

/** The idle band's line for one gym day. */
export interface DailySaying {
  readonly day: string;
  readonly saying: GymSaying;
}

/**
 * Today's line, kept while it is still live (#1462). The day seed picks it, as
 * always; but an admin adding or switching off another quote changes the
 * list it was picked from, and re-picking by index would change the line
 * mid-day. So the line already on the wall stays until the gym day changes or
 * that very quote is no longer in the list.
 */
export function keepDailySaying(
  previous: DailySaying | null,
  day: string,
  source: readonly GymSaying[],
): DailySaying | null {
  if (
    previous
    && previous.day === day
    && sayingsFor('anywhere', source).some(
      (s) => s.line === previous.saying.line && s.said_by === previous.saying.said_by,
    )
  ) {
    return previous;
  }
  const saying = pickSaying('anywhere', day, source);
  return saying ? { day, saying } : null;
}

/** One poll: the paired read first, the public read if this screen is not paired. */
export async function readBoard(base: string): Promise<{
  board: WallBoard;
  paired: boolean;
  timer: WallRoundTimer | null;
  quotes: LibraryQuote[] | null;
}> {
  const paired = await fetch(`${base}/api/pilot/tv/session`, {
    cache: 'no-store',
    // The device cookie is the credential. It is httpOnly and scoped to
    // /api/pilot/tv; there is no session cookie on a television to leak.
    credentials: 'include',
  });
  if (paired.status !== 401) {
    if (!paired.ok) throw new Error('unavailable');
    const payload = (await paired.json()) as PairedResponse;
    // board: null is the server's best-effort miss (gymTvs.ts): the session
    // read worked, the board read did not. The last board stays up, dated.
    const session = payload.session;
    const timer = session?.timer && session.run_id ? { runId: session.run_id, view: session.timer } : null;
    if (!payload.board) throw new BoardMissError(timer);
    return {
      board: payload.board,
      paired: true,
      timer,
      quotes: Array.isArray(payload.quotes) ? payload.quotes : null,
    };
  }

  /* credentials: 'omit' is stated rather than left to the default, and
     rather than taking a line in the convention test's allowlist. The gear
     shop established that pattern (#193): an explicit omission at the call
     site is a claim the reader can check, where an allowlist entry is a claim
     in another file that drifts away from the fetch it describes. Nobody
     signs in to a television, so there is no session cookie here to send --
     and /api/pilot/wall is built to be safe as a public document anyway: the
     organization is never taken from the caller, and the payload has no
     person in it at all (WallPublicBoard). */
  let payload: PublicResponse;
  try {
    const response = await fetch(`${base}/api/pilot/wall`, {
      cache: 'no-store',
      credentials: 'omit',
    });
    if (!response.ok) throw new Error('unavailable');
    payload = (await response.json()) as PublicResponse;
  } catch {
    throw new UnpairedReadError();
  }
  if (!payload.ok || !payload.board || payload.board.scope !== 'public') throw new UnpairedReadError();
  // The public board carries no quotes (OD-2026-10-07-008): an unpaired wall says the gym's own lines.
  return { board: publicToBoard(payload.board), paired: false, timer: null, quotes: [] };
}

export default function WallDisplay() {
  const [board, setBoard] = useState<WallBoard | null>(null);
  // The quotes last read (null on a failed quotes read keeps these), and the
  // day's line picked from them.
  const quotesRef = useRef<LibraryQuote[]>([]);
  const [daily, setDaily] = useState<DailySaying | null>(null);
  const [lastGoodAt, setLastGoodAt] = useState<number | null>(null);
  const [connected, setConnected] = useState(true);
  const [now, setNow] = useState<number | null>(null);
  // null until the first poll has answered: the pair box must not flash up
  // on a paired screen while the first read is still in flight.
  const [paired, setPaired] = useState<boolean | null>(null);
  const mounted = useRef(true);
  // Lets the pair box ask for a fresh read the moment a code is accepted,
  // instead of waiting out the thirty-second timer with "Nobody" on screen.
  const refreshRef = useRef<() => void>(() => {});
  // The round timer from the last good paired read, and when (by this TV's clock) it was read.
  const [roundTimer, setRoundTimer] = useState<(WallRoundTimer & { readAt: number }) | null>(null);
  // What the round sounds compare against, and every sound key already rung on this screen.
  const lastReading = useRef<{ runId: string; reading: WallRoundReading } | null>(null);
  const rung = useRef<Set<string>>(new Set());
  // Bumped for each new set of rounds on a run, so a second set rings its own bells.
  const setEpoch = useRef(0);

  /* The clock is read from the browser, not from the payload and not from the
     server. The television is in the room; its clock is the gym's clock, and it
     keeps telling the right time when the backend is down -- which is precisely
     when a blank screen would be most embarrassing.

     It starts null, and that is not an oversight. This route prerenders, so a
     clock initialised from Date.now() would be BUILD time: the shipped HTML
     said "Monday, August 3, 4:22 PM" and every browser showed that stale
     instant until hydration, on the one screen in the building whose entire
     job is to be true. Null renders a held space instead, and the first tick
     fills it. */
  useEffect(() => {
    // The wall clock IS an external system, and this is the subscribe step:
    // read it once on mount so the masthead fills immediately rather than
    // holding blank for the first second, then follow it. Same exemption
    // CoachWorkspace takes for its own on-mount reads.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setNow(Date.now());
    const tick = setInterval(() => setNow(Date.now()), 1_000);
    return () => clearInterval(tick);
  }, []);

  useEffect(() => {
    mounted.current = true;
    let timer: ReturnType<typeof setTimeout> | undefined;
    let failures = 0;
    // One read at a time. Without this, a visibilitychange arriving mid-request
    // starts a second poll, both finish and both schedule a timer, and only the
    // later one is tracked -- so the orphan keeps firing and the wall quietly
    // doubles its request rate every time the TV wakes up.
    let inFlight = false;
    // A round timer is set and not ended: poll fast (WALL_ROUND_POLL_MS).
    let roundsLive = false;

    async function poll(): Promise<void> {
      if (inFlight) return;
      inFlight = true;
      try {
        const { board: next, paired: isPaired, timer: nextTimer, quotes: library } = await readBoard(apiBase());
        if (!mounted.current) return;

        failures = 0;
        roundsLive = roundsAreLive(nextTimer);
        setBoard(next);
        if (library !== null) quotesRef.current = library;
        const source = sayingSource(quotesRef.current, 'anywhere');
        setDaily((previous) => keepDailySaying(previous, next.gym_day, source));
        setPaired(isPaired);
        setRoundTimer(nextTimer ? { ...nextTimer, readAt: Date.now() } : null);
        setLastGoodAt(Date.now());
        setConnected(true);
      } catch (error) {
        if (!mounted.current) return;
        failures += 1;
        setConnected(false);
        // The last good board deliberately stays on screen, dated. A wall that
        // blanks on a dropped packet is worse than one that admits its age --
        // except for the people on it, once the server has said this screen
        // is not paired (withoutPeople).
        if (error instanceof BoardMissError) {
          roundsLive = roundsAreLive(error.timer);
          setRoundTimer(error.timer ? { ...error.timer, readAt: Date.now() } : null);
        }
        if (!(error instanceof BoardMissError)) {
          // The read itself failed: no fresh timer, so back off as for any outage.
          roundsLive = false;
        }
        if (error instanceof UnpairedReadError) {
          setRoundTimer(null);
          setPaired(false);
          setBoard((previous) => (previous ? withoutPeople(previous) : previous));
          quotesRef.current = [];
          setDaily(null);
        }
      } finally {
        // In `finally` so the early returns above cannot leave the display
        // holding a lock it never releases -- a wall that stops asking is a
        // wall that is wrong for the rest of the evening.
        inFlight = false;
        if (mounted.current) {
          timer = setTimeout(() => void poll(), nextPollDelayMs(failures, roundsLive));
        }
      }
    }

    function refreshNow() {
      // A TV browser throttles or suspends a backgrounded tab; coming back
      // should not mean waiting out a timer that never fired.
      if (typeof document !== 'undefined' && document.visibilityState !== 'visible') return;
      if (timer) clearTimeout(timer);
      void poll();
    }

    void poll();
    refreshRef.current = () => {
      if (timer) clearTimeout(timer);
      void poll();
    };

    if (typeof document !== 'undefined') {
      document.addEventListener('visibilitychange', refreshNow);
    }

    return () => {
      mounted.current = false;
      if (timer) clearTimeout(timer);
      if (typeof document !== 'undefined') {
        document.removeEventListener('visibilitychange', refreshNow);
      }
    };
  }, []);

  // Before the clock has landed the board makes no claim about its own age.
  // Reading Date.now() here instead would be an impure call during render, and
  // the honest answer for that one frame is "nothing known yet" anyway.
  const health: WallHealth = now === null ? 'never' : boardHealth(lastGoodAt, now);
  const zone = board?.time_zone;
  const showLive = board !== null && health !== 'abandoned';
  // The round clock follows its own reading, not the board's: a paired read that brought a timer
  // but missed its board still shows and rings it. It goes when that reading is as old as an
  // abandoned board.
  const roundReading =
    roundTimer && now !== null && now - roundTimer.readAt < WALL_ABANDON_MS
      ? advanceRoundTimer(roundTimer.view, Math.floor((now - roundTimer.readAt) / 1000))
      : null;

  // The round bell and knock (WO-N1-04), through the app's one sound engine: silent unless the
  // TV's sound is on (the switch below arms it). Each sound has keys per set, round and event, and
  // a key rings at most once here, so a poll, a re-anchor or a network blip never repeats one. A
  // key is spent only when the engine actually played it: a bell dropped because another sound was
  // still ringing is tried again on the next tick while it is still fresh. The first reading after
  // a load rings nothing.
  useEffect(() => {
    if (!roundTimer || !roundReading) {
      lastReading.current = null;
      return;
    }
    const previous = lastReading.current?.runId === roundTimer.runId ? lastReading.current.reading : null;
    if (isNewSet(previous, roundReading, roundTimer.view, WALL_ROUND_FRESH_SECONDS)) setEpoch.current += 1;
    const setKey = `${roundTimer.runId}#${setEpoch.current}`;
    let dropped = false;
    for (const sound of roundSounds(setKey, previous, roundReading, roundTimer.view, WALL_ROUND_FRESH_SECONDS)) {
      if (sound.keys.every((key) => rung.current.has(key))) continue;
      if (!playGymSound(sound.voice)) {
        dropped = true;
        continue;
      }
      for (const key of sound.keys) rung.current.add(key);
    }
    // A dropped sound keeps the reading before it as the comparison, so the next tick sees the same
    // transition again; the freshness window bounds how long it is retried.
    if (!dropped || !previous) lastReading.current = { runId: roundTimer.runId, reading: roundReading };
  });

  return (
    <div className="wall-board ge-wallboard flex h-screen w-screen flex-col overflow-hidden">
      <Masthead
        now={now}
        zone={zone}
        round={roundTimer && roundReading ? <RoundPanel reading={roundReading} roundSeconds={roundTimer.view.round_seconds} /> : null}
      />

      {showLive ? (
        <LiveBoard board={board} zone={zone} daily={daily} />
      ) : (
        <StandingBoard health={health} />
      )}

      <FootRule board={showLive ? board : null} health={health} connected={connected} zone={zone} />
      {paired === false && <PairBox onPaired={() => refreshRef.current()} />}
      {paired === true && <WallSound />}
    </div>
  );
}

