/**
 * THE MARQUEE.
 *
 * .marquee did not exist in the design system. The Phase 2 roadmap says it did
 * -- "`.marquee` already exists in the design system with zero consumers" --
 * and that is simply not true of design-system/ppbf.css as it stands; it was
 * anticipated in prose and never written. The rules live in globals.css under
 * [data-surface="wall"], and wallSurface.test.tsx pins both halves together.
 *
 * It travels. On the brightest band of a screen that runs twelve hours a day,
 * continuously moving pixels is the single best burn-in defence available, and
 * a travelling sign is what a marquee IS. Under prefers-reduced-motion it
 * stops dead and becomes a list.
 */
function Marquee({ board, daily }: { board: WallBoard; daily: DailySaying | null }) {
  const items = board.marquee;

  if (items.length === 0) {
    /* No crossing in the window. The band stays -- a layout that reflows when
       news arrives draws the eye to the wrong thing -- and the gym says one of
       its own lines instead.

       THIS IS THE ROOM THE EGGS ARE FOR. The DNA names this screen in the gym
       floor's Purpose line and calls the floor the primary home of the words
       on the wall, and until now this file did not import them at all: the
       idle band recited the Fibonacci ladder, which is true but is a fact
       about the software. The ladder stays as the fallback below, for the
       state the source is built to have -- gymSayings.ts renders nothing
       rather than borrow somebody else's words, and an empty band on a
       television is not an option.

       SEEDED BY THE GYM'S OWN DAY, so the line is fixed for the whole day and
       changes at the gym's midnight. Never random: this screen is on a wall
       for twelve hours in front of the room, and a sign that says something
       different every thirty-second poll is a slot machine bolted above the
       heavy bags. board.gym_day is computed server-side in the gym's own time
       zone, which also keeps this off the browser clock -- the one thing this
       prerendered route cannot read during a render without lying for a frame.

       .wallwords is deliberately NOT used here, though it is the same object
       elsewhere: it paints at --t-lg, a desk size, and this screen's body type
       starts two rungs above that. The marquee's own idle chrome is the wall's
       lettering slot, already sized for fifteen feet, and the attribution sits
       in the label the band already has. */
    // From the gym's quote library on a paired TV (#1462 Q-A), the gym's own
    // GYM_SAYINGS otherwise; the same day seed either way, and kept for the
    // day while it stays live (keepDailySaying).
    const saying = daily && daily.day === board.gym_day ? daily.saying : pickSaying('anywhere', board.gym_day);
    return (
      <section className="marquee marquee--idle" aria-label={saying ? 'Words on the wall' : 'Milestones'}>
        {saying ? (
          <p className="marquee-idle-line">
            <span className="marquee-idle-label">{saying.said_by}</span>
            <span>{saying.line}</span>
          </p>
        ) : (
          <p className="marquee-idle-line">
            <span className="marquee-idle-label">The ladder</span>
            <span aria-hidden="true">5 · 13 · 34 · 89 · 233</span>
            <span className="sr-only">5, 13, 34, 89, 233 sessions</span>
          </p>
        )}
      </section>
    );
  }

  // Duration scales with content so the travel SPEED is constant however many
  // names are up: eight seconds of screen time per name.
  const seconds = Math.max(24, items.length * 8);

  return (
    <section className="marquee" aria-label="Milestones">
      <div className="marquee-track" style={{ ['--marquee-secs' as string]: `${seconds}s` }}>
        {/* Two passes of the same list make the loop seamless. The second is
            hidden from the accessibility tree so a reader is not told the same
            child crossed the same milestone twice. */}
        <ul className="marquee-run">
          {items.map((item) => (
            <li key={item.key} className="marquee-item">
              <span className="marquee-mark" aria-hidden="true">
                ★
              </span>
              <span className="marquee-name">{item.name}</span>
              <span className="marquee-count">{item.milestone}</span>
              <span className="marquee-unit">sessions</span>
            </li>
          ))}
        </ul>
        <ul className="marquee-run" aria-hidden="true">
          {items.map((item) => (
            <li key={`echo-${item.key}`} className="marquee-item">
              <span className="marquee-mark">★</span>
              <span className="marquee-name">{item.name}</span>
              <span className="marquee-count">{item.milestone}</span>
              <span className="marquee-unit">sessions</span>
            </li>
          ))}
        </ul>
      </div>
    </section>
  );
}

